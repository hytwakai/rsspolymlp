"""Interfaces for pypolymlp."""

from typing import Optional

import numpy as np

from pypolymlp.core.data_format import PolymlpStructure


def gen_polymlp_structure(
    axis: np.ndarray,
    positions: np.ndarray,
    elements: np.ndarray,
    comment: Optional[np.ndarray] = None,
):
    """
    Convention
    ----------
    axis : (3, 3) array_like
        Each row represents one lattice vector (a, b, or c).
        Equivalent to np.array([[a1, a2, a3], [b1, b2, b3], [c1, c2, c3]]).
    positions : (N, 3) array_like
        Fractional atomic coordinates within the unit cell.
        Each row represents the coordinates of one atom.
    elements : (N,) array_like
        Chemical element symbols corresponding to the atomic positions.
    """
    if comment is None:
        comment = "Generated by rsspolymlp"

    types = []
    element_types = {}
    for e in elements:
        if e not in element_types:
            element_types[e] = len(element_types)
        types.append(element_types[e])

    n_types = len(set(elements))
    type_list = list(range(0, n_types))
    n_atoms = [types.count(t_ref) for t_ref in type_list]

    return PolymlpStructure(
        axis=axis.T,
        positions=positions.T,
        n_atoms=n_atoms,
        elements=elements,
        types=types,
        volume=np.linalg.det(axis),
        comment=comment,
    )
