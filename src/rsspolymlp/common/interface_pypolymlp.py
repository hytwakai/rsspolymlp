"""Interfaces for pypolymlp."""

from typing import Optional

import numpy as np

from pypolymlp.core.data_format import PolymlpStructure


def gen_polymlp_structure(
    axis: np.ndarray,
    positions: np.ndarray,
    elements: np.ndarray,
    comment: Optional[np.ndarray] = None,
):
    if comment is None:
        comment = "Generated by rsspolymlp"

    types = []
    element_types = {}
    for e in elements:
        if e not in element_types:
            element_types[e] = len(element_types)
        types.append(element_types[e])

    n_types = len(set(elements))
    type_list = list(range(0, n_types))
    n_atoms = [types.count(t_ref) for t_ref in type_list]

    return PolymlpStructure(
        axis=axis.T,
        positions=positions.T,
        n_atoms=n_atoms,
        elements=elements,
        types=types,
        volume=np.linalg.det(axis),
        comment=comment,
    )
